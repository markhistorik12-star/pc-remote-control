    public InstalledAppsService(AgentConfigService config)
    {
        _config = config;
        EnsureDefaultAppsInitialized();
    }

    public void TrimIconCache()
    {
        var keepIds = _config.GetSelectedApps().Select(a => a.Id).ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var key in _iconPngCache.Keys)
        {
            if (!keepIds.Contains(key))
            {
                _iconPngCache.TryRemove(key, out _);
            }
        }
    }

    private void EnsureDefaultAppsInitialized()
    {
        if (_config.HasInitializedApps()) return;

        var discovered = GetDiscoveredApps(forceRefresh: true);
        var defaults = new List<SavedAppEntry>();

        foreach (var app in discovered)
        {
            var lowerName = app.Name.ToLowerInvariant();
            if (app.Kind is "browser" or "steam" ||
                lowerName is "spotify" or "discord" or "chatgpt" or "calculadora" or "bloc de notas" or "explorador de archivos" or "paint")
            {
                defaults.Add(ToSavedEntry(app));
            }
        }

        _config.SaveSelectedApps(defaults.Take(10));
    }

    public IReadOnlyList<AppCatalogItem> GetSelectedAppsList()
    {
        var saved = _config.GetSelectedApps();
        return saved
            .Select(s =>
            {
                var kind = s.Kind == "standard" ? ClassifyKind(s.Name, s.LaunchTarget, s.ExePath) : s.Kind;
                return new AppCatalogItem(s.Id, s.Name, s.LaunchTarget, s.ExePath, s.Arguments, kind, true);
            })
            .ToList();
    }

    public IReadOnlyList<AppCatalogItem> GetFullCatalog(bool forceRefresh = false)
    {
        var saved = _config.GetSelectedApps();
        var selectedIds = saved.Select(s => s.Id).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var discovered = GetDiscoveredApps(forceRefresh);

        var map = new Dictionary<string, SavedAppEntry>(StringComparer.OrdinalIgnoreCase);
        foreach (var d in discovered)
        {
            map[d.Id] = ToSavedEntry(d);
        }
        foreach (var custom in _config.GetCustomApps())
        {
            map[custom.Id] = custom;
        }
        foreach (var s in saved)
        {
            if (!map.ContainsKey(s.Id)) map[s.Id] = s;
        }

        return map.Values
            .Select(e => new AppCatalogItem(
                e.Id,
                e.Name,
                e.LaunchTarget,
                e.ExePath,
                e.Arguments,
                e.Kind,
                selectedIds.Contains(e.Id)))
            .OrderByDescending(a => a.Selected)
            .ThenBy(a => a.Kind switch { "browser" => 0, "steam" => 1, "game" => 2, _ => 3 })
            .ThenBy(a => a.Name, StringComparer.CurrentCultureIgnoreCase)
            .ToList();
    }

    public (bool Success, string Message, AppCatalogItem? Added) AddCustomExe(string name, string exePath)
    {
        var cleanPath = exePath.Trim().Trim('"');
        if (!File.Exists(cleanPath) || !cleanPath.EndsWith(".exe", StringComparison.OrdinalIgnoreCase))
        {
            return (false, "No se encontró el archivo .exe en esa ruta.", null);
        }

        var cleanName = string.IsNullOrWhiteSpace(name)
            ? Path.GetFileNameWithoutExtension(cleanPath)
            : name.Trim();

        var id = ComputeId(cleanPath);
        var kind = ClassifyKind(cleanName, cleanPath, cleanPath);
        var entry = new SavedAppEntry(id, cleanName, cleanPath, cleanPath, "", kind);
        _config.AddCustomApp(entry);

        return (true, $"{cleanName} agregada a tus aplicaciones",
            new AppCatalogItem(id, cleanName, cleanPath, cleanPath, "", kind, true));
    }

    public SavedAppEntry? FindAppById(string id)
    {
        var selected = _config.GetSelectedApps()
            .FirstOrDefault(a => a.Id.Equals(id, StringComparison.OrdinalIgnoreCase));
        if (selected != null) return selected;

        var custom = _config.GetCustomApps()
            .FirstOrDefault(a => a.Id.Equals(id, StringComparison.OrdinalIgnoreCase));
        if (custom != null) return custom;

        var disc = GetDiscoveredApps(forceRefresh: false)
            .FirstOrDefault(a => a.Id.Equals(id, StringComparison.OrdinalIgnoreCase));
        return disc != null ? ToSavedEntry(disc) : null;
    }

    public byte[]? GetIconPngById(string id)
    {
        if (_iconPngCache.TryGetValue(id, out var cached))
        {
            return cached;
        }

        byte[]? png = null;
        var disc = GetDiscoveredApps(forceRefresh: false)
            .FirstOrDefault(a => a.Id.Equals(id, StringComparison.OrdinalIgnoreCase));

        if (disc != null)
        {
            foreach (var source in disc.IconSources)
            {
                png = TryExtractOrReadIcon(source);
                if (png is { Length: > 100 }) break;
            }
        }
        else
        {
            var saved = FindAppById(id);
            if (saved != null)
            {
                if (!string.IsNullOrWhiteSpace(saved.LaunchTarget))
                    png = TryExtractOrReadIcon(saved.LaunchTarget);
                if (png is null && !string.IsNullOrWhiteSpace(saved.ExePath))
                    png = TryExtractOrReadIcon(saved.ExePath);
            }
        }

        _iconPngCache[id] = png;
        return png;
    }

    private static byte[]? TryExtractOrReadIcon(string source)
    {
        if (string.IsNullOrWhiteSpace(source)) return null;

        // Direct image file (e.g. Steam librarycache icon jpg/png)
        if ((source.EndsWith(".jpg", StringComparison.OrdinalIgnoreCase) ||
             source.EndsWith(".png", StringComparison.OrdinalIgnoreCase)) &&
            File.Exists(source))
        {
            try
            {
                using var img = System.Drawing.Image.FromFile(source);
                using var bmp = new System.Drawing.Bitmap(64, 64, System.Drawing.Imaging.PixelFormat.Format32bppArgb);
                using (var g = System.Drawing.Graphics.FromImage(bmp))
                {
                    g.InterpolationMode = System.Drawing.Drawing2D.InterpolationMode.HighQualityBicubic;
                    g.DrawImage(img, 0, 0, 64, 64);
                }
                using var ms = new MemoryStream();
                bmp.Save(ms, System.Drawing.Imaging.ImageFormat.Png);
                return ms.ToArray();
            }
            catch { }
        }

        return ShellIconExtractor.ExtractPngBytes(source, 64);
    }

    private record RawDiscoveredApp(
        string Id,
        string Name,
        string LaunchTarget,
        string ExePath,
        string Arguments,
        string Kind,
        List<string> IconSources
    );

    private static SavedAppEntry ToSavedEntry(RawDiscoveredApp d) =>
        new(d.Id, d.Name, d.LaunchTarget, d.ExePath, d.Arguments, d.Kind);

    private List<RawDiscoveredApp> GetDiscoveredApps(bool forceRefresh)
    {
        lock (_scanLock)
        {
            if (!forceRefresh && _lastScanCache != null && (DateTime.UtcNow - _lastScanTime).TotalSeconds < 45)
            {
                return _lastScanCache;
            }

            _lastScanCache = ScanAllSources();
            _lastScanTime = DateTime.UtcNow;
            return _lastScanCache;
        }
    }

    private static List<RawDiscoveredApp> ScanAllSources()
    {
        // Map of Start Menu shortcut friendlyName -> (.lnk path, resolved .exe, args)
        var lnkLookup = BuildShortcutLookup();
        var results = new Dictionary<string, RawDiscoveredApp>(StringComparer.OrdinalIgnoreCase);
        var seenNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        void AddCandidate(string rawName, string launchTarget, string exePath, string args, List<string> iconSources, string? forcedKind = null)
        {
            var cleanName = rawName.Replace('\u00A0', ' ').Trim();
            if (cleanName.Length < 2) return;
            if (IsNoiseApp(cleanName, launchTarget, exePath)) return;
            if (seenNames.Contains(cleanName)) return;

            var keySource = !string.IsNullOrWhiteSpace(exePath) ? exePath : launchTarget;
            var id = ComputeId(keySource);
            if (results.ContainsKey(id)) return;

            var kind = forcedKind ?? ClassifyKind(cleanName, launchTarget, exePath);
            results[id] = new RawDiscoveredApp(id, cleanName, launchTarget, exePath, args, kind, iconSources);
            seenNames.Add(cleanName);
        }

        // 1. Primary source: Windows 11 Start Menu AppsFolder (Win32 + Microsoft Store UWP + Launchers + Games)
        var folderId = FOLDERID_AppsFolder;
        var shellItemGuid = IID_IShellItem;
        if (SHGetKnownFolderItem(ref folderId, 0, IntPtr.Zero, ref shellItemGuid, out var appsFolder) == 0 && appsFolder != null)
        {
            try
            {
                var enumGuid = BHID_EnumItems;
                var ienumGuid = IID_IEnumShellItems;
                if (appsFolder.BindToHandler(IntPtr.Zero, ref enumGuid, ref ienumGuid, out var enumerator) == 0 && enumerator != null)
                {
                    try
                    {
                        while (enumerator.Next(1, out var item, out var fetched) == 0 && fetched == 1 && item != null)
                        {
                            try
                            {
                                item.GetDisplayName(SIGDN_NORMALDISPLAY, out var displayName);
                                item.GetDisplayName(SIGDN_PARENTRELATIVEPARSING, out var appId);

                                if (string.IsNullOrWhiteSpace(displayName) || string.IsNullOrWhiteSpace(appId))
                                    continue;

                                var cleanName = displayName.Replace('\u00A0', ' ').Trim();
                                var shellLaunch = $"shell:AppsFolder\\{appId}";
                                var exePath = "";
                                var args = "";
                                var iconSources = new List<string> { shellLaunch };

                                if (lnkLookup.TryGetValue(cleanName, out var lnkInfo))
                                {
                                    exePath = lnkInfo.ExePath;
                                    args = lnkInfo.Args;
                                    iconSources.Add(lnkInfo.LnkPath);
                                    if (!string.IsNullOrWhiteSpace(exePath)) iconSources.Add(exePath);
                                }
                                else if (File.Exists(appId) && appId.EndsWith(".exe", StringComparison.OrdinalIgnoreCase))
                                {
                                    exePath = appId;
                                    iconSources.Add(appId);
                                }

                                // Steam game shortcut via AppsFolder
                                if (appId.StartsWith("steam://rungameid/", StringComparison.OrdinalIgnoreCase))
                                {
                                    var steamAppId = appId["steam://rungameid/".Length..].Trim();
                                    iconSources.Insert(0, GetSteamGameIconCandidate(steamAppId));
                                    AddCandidate(cleanName, appId, "", "", iconSources, "game");
                                    continue;
                                }

                                AddCandidate(cleanName, shellLaunch, exePath, args, iconSources);
                            }
                            finally
                            {
                                Marshal.ReleaseComObject(item);
                            }
                        }
                    }
                    finally
                    {
                        Marshal.ReleaseComObject(enumerator);
                    }
                }
            }
            finally
            {
                Marshal.ReleaseComObject(appsFolder);
            }
        }

        // 2. Installed Steam Games from libraryfolders.vdf / appmanifest_*.acf
        ScanSteamInstalledGames((gameName, appId, iconList) =>
        {
            AddCandidate(gameName, $"steam://rungameid/{appId}", "", "", iconList, "game");
        });

        // 3. Ensure core Windows essentials are always available cleanly
        var winDir = Environment.GetFolderPath(Environment.SpecialFolder.Windows);
        var explorerExe = Path.Combine(winDir, "explorer.exe");
        AddCandidate("Explorador de archivos", explorerExe, explorerExe, "", [explorerExe], "standard");

        return results.Values.ToList();
    }

    private static Dictionary<string, (string LnkPath, string ExePath, string Args)> BuildShortcutLookup()
    {
        var dict = new Dictionary<string, (string, string, string)>(StringComparer.OrdinalIgnoreCase);
        var startDirs = new[]
        {
            Environment.GetFolderPath(Environment.SpecialFolder.CommonPrograms),
            Environment.GetFolderPath(Environment.SpecialFolder.Programs)
        };

        foreach (var dir in startDirs)
        {
            if (string.IsNullOrWhiteSpace(dir) || !Directory.Exists(dir)) continue;
            IEnumerable<string> files;
            try { files = Directory.EnumerateFiles(dir, "*.lnk", SearchOption.AllDirectories); }
            catch { continue; }

            foreach (var lnk in files)
            {
                var name = Path.GetFileNameWithoutExtension(lnk).Trim();
                if (dict.ContainsKey(name)) continue;
                var resolved = ShortcutResolver.Resolve(lnk);
                if (resolved != null && File.Exists(resolved.Value.TargetPath))
                {
                    dict[name] = (lnk, resolved.Value.TargetPath, resolved.Value.Arguments);
                }
            }
        }
        return dict;
    }

    private static void ScanSteamInstalledGames(Action<string, string, List<string>> onGame)
    {
        var steamDir = SteamService.GetSteamDir();
        if (steamDir is null) return;

        var steamFolders = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { steamDir };
        var libVdf = Path.Combine(steamDir, "steamapps", "libraryfolders.vdf");
        if (File.Exists(libVdf))
        {
            try
            {
                var vdfText = File.ReadAllText(libVdf);
                foreach (Match m in Regex.Matches(vdfText, @"""path""\s+""([^""]+)"""))
                {
                    var p = m.Groups[1].Value.Replace(@"\\", @"\");
                    if (Directory.Exists(p)) steamFolders.Add(p);
                }
            }
            catch { }
        }

        foreach (var lib in steamFolders)
        {
            var appsDir = Path.Combine(lib, "steamapps");
            if (!Directory.Exists(appsDir)) continue;

            IEnumerable<string> manifests;
            try { manifests = Directory.EnumerateFiles(appsDir, "appmanifest_*.acf"); }
            catch { continue; }

            foreach (var acf in manifests)
            {
                try
                {
                    var txt = File.ReadAllText(acf);
                    var idMatch = Regex.Match(txt, @"""appid""\s+""(\d+)""");
                    var nameMatch = Regex.Match(txt, @"""name""\s+""([^""]+)""");
                    if (!idMatch.Success || !nameMatch.Success) continue;

                    var appId = idMatch.Groups[1].Value;
                    var name = nameMatch.Groups[1].Value.Trim();

                    // Skip Steamworks Common Redistributables / Proton / SDKs
                    if (appId == "228980" ||
                        name.Contains("Redistributable", StringComparison.OrdinalIgnoreCase) ||
                        name.Contains("Soundtrack", StringComparison.OrdinalIgnoreCase) ||
                        name.Contains("Dedicated Server", StringComparison.OrdinalIgnoreCase))
                        continue;

                    var icons = new List<string>();
                    var cacheIcon = GetSteamGameIconCandidate(appId);
                    if (!string.IsNullOrEmpty(cacheIcon)) icons.Add(cacheIcon);
                    icons.Add(Path.Combine(steamDir, "steam.exe"));

                    onGame(name, appId, icons);
                }
                catch { }
            }
        }
    }

    private static string GetSteamGameIconCandidate(string steamAppId)
    {
        var steamDir = SteamService.GetSteamDir();
        if (steamDir is null) return "";

        var libCacheDir = Path.Combine(steamDir, "appcache", "librarycache");
        if (Directory.Exists(libCacheDir))
        {
            // Modern Steam stores icons in librarycache\<appid>\*_icon.jpg or librarycache\<appid>_icon.jpg
            var flatIcon = Path.Combine(libCacheDir, $"{steamAppId}_icon.jpg");
            if (File.Exists(flatIcon)) return flatIcon;

            var subDir = Path.Combine(libCacheDir, steamAppId);
            if (Directory.Exists(subDir))
            {
                try
                {
                    var iconFile = Directory.EnumerateFiles(subDir, "*.jpg")
                        .OrderBy(f => f.Contains("icon", StringComparison.OrdinalIgnoreCase) ? 0 : 1)
                        .FirstOrDefault();
                    if (iconFile != null) return iconFile;
                }
                catch { }
            }
        }
        return "";
    }

    private static bool IsNoiseApp(string name, string launchTarget, string exePath)
    {
        if (ExcludedNameSubstrings.Any(k => name.Contains(k, StringComparison.OrdinalIgnoreCase)))
            return true;

        var rawTarget = launchTarget.StartsWith("shell:AppsFolder\\", StringComparison.OrdinalIgnoreCase)
            ? launchTarget["shell:AppsFolder\\".Length..]
            : launchTarget;

        if (ExcludedAppIdSubstrings.Any(k => rawTarget.Contains(k, StringComparison.OrdinalIgnoreCase)))
            return true;

        if (!string.IsNullOrWhiteSpace(exePath) &&
            ExcludedAppIdSubstrings.Any(k => exePath.Contains(k, StringComparison.OrdinalIgnoreCase)))
            return true;

        return false;
    }

    private static string ClassifyKind(string name, string launchTarget, string exePath)
    {
        var exeName = Path.GetFileName(exePath);
        if (BrowserExes.Contains(exeName) || BrowserNames.Contains(name.Trim()))
            return "browser";

        if (exeName.Equals("notepad.exe", StringComparison.OrdinalIgnoreCase) ||
            launchTarget.Contains("Microsoft.WindowsNotepad", StringComparison.OrdinalIgnoreCase) ||
            name.Trim().Equals("Bloc de notas", StringComparison.OrdinalIgnoreCase) ||
            name.Trim().Equals("Notepad", StringComparison.OrdinalIgnoreCase))
            return "notepad";

        if (exeName.Equals("steam.exe", StringComparison.OrdinalIgnoreCase) ||
            name.Equals("Steam", StringComparison.OrdinalIgnoreCase))
            return "steam";

        if (launchTarget.StartsWith("steam://rungameid/", StringComparison.OrdinalIgnoreCase) ||
            launchTarget.StartsWith("googleplaygames://", StringComparison.OrdinalIgnoreCase) ||
            GameLaunchers.Contains(name.Trim()))
            return "game";

        return "standard";
    }

    private static string ComputeId(string keySource)
    {
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes(keySource.Trim().ToLowerInvariant()));
        return Convert.ToHexString(hash)[..12].ToLowerInvariant();
    }
